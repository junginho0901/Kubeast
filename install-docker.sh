#!/usr/bin/env bash
#
# Kubeast Docker Installer
#
# Usage:
#   ./install-docker.sh
#   ./install-docker.sh --port 9000
#   ./install-docker.sh --uninstall
#
# The cluster is connected in the browser after the first sign-in (Setup page).
#
set -euo pipefail

# Defaults
PORT="8000"
SKIP_ENV=false
UNINSTALL=false

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

info()  { echo -e "${CYAN}[kubeast]${NC} $1"; }
ok()    { echo -e "${GREEN}[kubeast]${NC} $1"; }
warn()  { echo -e "${YELLOW}[kubeast]${NC} $1"; }
fail()  { echo -e "${RED}[kubeast]${NC} $1"; exit 1; }

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Parse args
while [[ $# -gt 0 ]]; do
  case "$1" in
    --kubeconfig)    warn "--kubeconfig is not used: connect the cluster on the Setup page after signing in."; shift 2 ;;
    --port)          PORT="$2"; shift 2 ;;
    --skip-env)      SKIP_ENV=true; shift ;;
    --uninstall)     UNINSTALL=true; shift ;;
    --help|-h)
      echo "Kubeast Docker Installer"
      echo ""
      echo "Usage: ./install-docker.sh [OPTIONS]"
      echo ""
      echo "Options:"
      echo "  --port <port>        Gateway port (default: 8000)"
      echo "  --skip-env           Skip .env generation (use existing .env)"
      echo "  --uninstall          Stop and remove all containers/volumes"
      echo "  -h, --help           Show this help"
      exit 0
      ;;
    *) fail "Unknown option: $1" ;;
  esac
done

# ─── Uninstall ───
if [[ "$UNINSTALL" == "true" ]]; then
  info "Stopping Kubeast..."
  cd "$ROOT"
  docker compose down -v 2>/dev/null || docker-compose down -v 2>/dev/null || true
  ok "Kubeast has been removed (containers + volumes deleted)."
  exit 0
fi

# ─── Pre-flight checks ───
info "Checking prerequisites..."

if command -v docker compose >/dev/null 2>&1; then
  COMPOSE="docker compose"
elif command -v docker-compose >/dev/null 2>&1; then
  COMPOSE="docker-compose"
else
  fail "docker compose not found. Install Docker Desktop or docker-compose: https://docs.docker.com/compose/install/"
fi

docker info >/dev/null 2>&1 || fail "Docker daemon is not running. Start Docker first."
ok "Docker is ready"

# ─── Generate .env ───
if [[ "$SKIP_ENV" == "true" && -f "$ROOT/.env" ]]; then
  ok "Using existing .env (--skip-env)"
else
  info "Generating .env file..."

  # A rerun keeps the values of the previous .env: the database volume keeps the password it was created with.
  previous() { [[ -f "$ROOT/.env" ]] && grep "^$1=" "$ROOT/.env" | head -1 | cut -d= -f2- || true; }
  POSTGRES_PW=$(previous POSTGRES_PASSWORD)
  POSTGRES_PW=${POSTGRES_PW:-$(openssl rand -base64 18 | tr -dc 'a-zA-Z0-9' | head -c 20)}
  ADMIN_PW=$(previous DEFAULT_ADMIN_PASSWORD)
  ADMIN_PW=${ADMIN_PW:-$(openssl rand -base64 18 | tr -dc 'a-zA-Z0-9' | head -c 20)}
  APPROVAL_SECRET=$(previous AI_APPROVAL_SECRET)
  APPROVAL_SECRET=${APPROVAL_SECRET:-$(openssl rand -hex 32)}
  INTERNAL_TOKEN=$(previous INTERNAL_API_TOKEN)
  INTERNAL_TOKEN=${INTERNAL_TOKEN:-$(openssl rand -hex 20)}
  # 비어 있으면 빈 문자열로 둔다. 부팅 후 Admin > AI Models 에서 등록.
  OPENAI_KEY=$(previous OPENAI_API_KEY)

  cat > "$ROOT/.env" <<ENVEOF
# ─── Generated by install-docker.sh ───
# LLM (비워두면 Admin UI 에서 등록)
OPENAI_API_KEY=${OPENAI_KEY}
OPENAI_MODEL=gpt-4o-mini
# OPENAI_BASE_URL=

# Application
APP_NAME=Kubeast
APP_VERSION=1.0.0
DEBUG=false

# CORS
ALLOWED_ORIGINS=http://localhost:${PORT},http://localhost:5173

# Auth/JWT
JWT_ISSUER=kubeast-auth
JWT_AUDIENCE=kubeast
DEFAULT_ADMIN_EMAIL=admin
DEFAULT_ADMIN_PASSWORD=${ADMIN_PW}
KEY_DIR=/app/.keys
# Shared by ai-service and tool-server to sign/verify AI write-tool approvals
AI_APPROVAL_SECRET=${APPROVAL_SECRET}
# Service-to-service token for k8s-service's /internal routes (tool-server, auth-service)
INTERNAL_API_TOKEN=${INTERNAL_TOKEN}

# Database
POSTGRES_USER=kubeast
POSTGRES_PASSWORD=${POSTGRES_PW}
POSTGRES_DB=kubeast

# Redis
REDIS_HOST=redis
REDIS_PORT=6379
REDIS_DB=0

# Kubernetes
KUBECONFIG_PATH=/app/kubeconfig.yaml
IN_CLUSTER=false

# Frontend
VITE_API_URL=http://localhost:${PORT}
VITE_WS_URL=ws://localhost:${PORT}
ENVEOF

  ok ".env generated (passwords auto-generated)"
fi

# ─── Gateway port (docker-compose.yml publishes ${GATEWAY_PORT:-8000}) ───
if grep -q '^GATEWAY_PORT=' "$ROOT/.env"; then
  sed -i.bak "s/^GATEWAY_PORT=.*/GATEWAY_PORT=${PORT}/" "$ROOT/.env" && rm -f "$ROOT/.env.bak"
else
  printf '\nGATEWAY_PORT=%s\n' "$PORT" >> "$ROOT/.env"
fi

# ─── Build & Start ───
echo ""
echo -e "${BOLD}Starting Kubeast...${NC}"
echo -e "  Gateway port: ${CYAN}${PORT}${NC}"
echo ""

cd "$ROOT"
# Pull the published ghcr.io images (no local build needed). Contributors who
# want to build from source: add  -f docker-compose.build.yml ... up -d --build
$COMPOSE pull 2>&1 || warn "Some images could not be pulled yet; continuing."
$COMPOSE up -d 2>&1

# ─── Wait for services ───
info "Waiting for services to be healthy..."

wait_for_healthy() {
  local service="$1"
  local max_wait="${2:-60}"
  local elapsed=0
  while [[ $elapsed -lt $max_wait ]]; do
    local status
    status=$($COMPOSE ps --format json "$service" 2>/dev/null | grep -o '"Health":"[^"]*"' | cut -d'"' -f4 || echo "")
    if [[ "$status" == "healthy" ]]; then
      return 0
    fi
    sleep 2
    elapsed=$((elapsed + 2))
  done
  return 1
}

if wait_for_healthy postgres 60; then
  ok "PostgreSQL is healthy"
else
  warn "PostgreSQL may still be starting..."
fi

if wait_for_healthy redis 30; then
  ok "Redis is healthy"
else
  warn "Redis may still be starting..."
fi

# Sign-in works once auth-service answers through the gateway (the gateway's own /health answers without it).
elapsed=0
until curl -sf "http://localhost:${PORT}/api/v1/auth/setup" >/dev/null 2>&1; do
  if [[ $elapsed -ge 120 ]]; then
    fail "auth-service is not answering on http://localhost:${PORT}. See: $COMPOSE logs auth-service"
  fi
  sleep 2
  elapsed=$((elapsed + 2))
done
ok "Sign-in is ready"

# ─── Access info ───
echo ""
echo -e "${GREEN}╔══════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║          Kubeast is ready! (Docker)              ║${NC}"
echo -e "${GREEN}╚══════════════════════════════════════════════════╝${NC}"
echo ""
echo -e "  Open: ${BOLD}http://localhost:${PORT}${NC}"
echo ""
echo "  Default account:"
echo "    ID:       admin"
ADMIN_PW_DISPLAY=$(grep '^DEFAULT_ADMIN_PASSWORD=' "$ROOT/.env" | cut -d= -f2-)
echo -e "    Password: ${BOLD}${ADMIN_PW_DISPLAY}${NC}"
echo -e "    ${YELLOW}!! Login 후 즉시 비밀번호를 변경하세요.${NC}"
echo ""
echo "  Next steps:"
echo "    1. Open the URL above"
echo "    2. Sign in with admin account"
echo "    3. On the Setup page, paste the kubeconfig of the cluster to manage."
echo "       Its server address must be reachable from the containers (not 127.0.0.1)."
echo "    4. Add your AI provider there or later in Admin > AI Models"
echo ""
echo -e "  Logs:      ${CYAN}docker compose logs -f${NC}"
echo -e "  Stop:      ${CYAN}docker compose down${NC}"
echo -e "  Uninstall: ${CYAN}./install-docker.sh --uninstall${NC}"
echo ""
